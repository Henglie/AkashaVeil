std::wstring choose_language(const std::wstring& requested, const std::wstring& system) {
    auto s = requested == L"auto" ? system : requested;
    std::transform(s.begin(), s.end(), s.begin(), [](wchar_t c) { return static_cast<wchar_t>(std::towlower(c)); });
    std::replace(s.begin(), s.end(), L'_', L'-');
    if (s == L"zh-hant" || s.rfind(L"zh-hant-", 0) == 0 || s == L"zh-tw" || s == L"zh-hk" || s == L"zh-mo") return L"en";
    if (s == L"zh" || s == L"zh-cn" || s == L"zh-sg" || s == L"zh-hans" || s.rfind(L"zh-hans-", 0) == 0) return L"zh";
    for (const wchar_t* code : {L"es", L"fr", L"ru", L"ar", L"tr", L"ja", L"ko"}) {
        const std::wstring prefix = std::wstring(code) + L"-";
        if (s == code || s.rfind(prefix, 0) == 0) return code;
    }
    return L"en";
}
