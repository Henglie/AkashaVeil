const wchar_t* text(Text key, const std::wstring& language) {
    const auto i = static_cast<unsigned>(key);
    if (i >= static_cast<unsigned>(Text::count)) return L"?";
    if (language != L"zh" && language != L"en") {
        if (const auto* table = locale_table(language, false)) return table[i];
    }
    const auto& e = entries[i];
    return language == L"zh" && e.zh && *e.zh ? e.zh : e.en;
}

